    <h5>Mise en page</h5>
    <p>Attention, veuillez utiliser ces methodes à la lettre sous peine de bugger le site.</p>
    <p>Il est possible de mettre en page vous même votre texte. Pour cela il faut utiliser une balise. Une balise est un code qui va encadrer
    le texte que vous souhaitez mettre en page</p>
    <p>Pour mettre du texte en gras: &lt;b&gt Mon texte &lt;/b&gt => <b>Mon texte</b></p>
    <p>Pour mettre un titre: &lt;h3&gt Mon texte &lt;/h3&gt => <span style="font-size: 20px">Mon texte</span></p>
    <p>Pour mettre un lien: &lta href="url de mon lien" &gt Mon texte &lt;/a&gt => <a href="https://www.google.com/">Mon texte</a></p>
</div>
